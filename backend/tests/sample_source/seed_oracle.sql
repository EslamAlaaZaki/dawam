-- Users: a read-only one DAWAM should be given, and one that can write (the warning).
CREATE USER dawam_reader IDENTIFIED BY "reader-secret"
/
CREATE USER dawam_writer IDENTIFIED BY "writer-secret"
/
GRANT CREATE SESSION TO dawam_reader, dawam_writer
/
BEGIN
    FOR o IN (SELECT owner, object_name FROM all_objects
              WHERE owner IN ('CORE', 'CRM', 'RESTRICTED')
                AND object_type IN ('TABLE', 'VIEW')) LOOP
        EXECUTE IMMEDIATE 'GRANT SELECT ON "' || o.owner || '"."' || o.object_name
            || '" TO dawam_reader, dawam_writer';
    END LOOP;
    FOR o IN (SELECT owner, object_name FROM all_objects
              WHERE owner = 'CORE' AND object_type IN ('FUNCTION', 'PROCEDURE')) LOOP
        EXECUTE IMMEDIATE 'GRANT EXECUTE ON "' || o.owner || '"."' || o.object_name
            || '" TO dawam_reader, dawam_writer';
    END LOOP;
END;
/
GRANT INSERT, UPDATE ON core.customers TO dawam_writer
/
