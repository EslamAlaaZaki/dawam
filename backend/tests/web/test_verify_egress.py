"""The by-hand egress check must fail closed: its judges pass only on a refusal's own marks. The
script itself needs a running network, so only these pure parts run here."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

PATH = Path(__file__).resolve().parents[3] / "deploy" / "crawl4ai" / "verify-egress.py"
TARGET = "http://169.254.169.254/"


@pytest.fixture(scope="module")
def verify():
    spec = importlib.util.spec_from_file_location("verify_egress", PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def response(status=403, *, headers=None, text=""):
    return {
        "event_type": "response",
        "url": TARGET,
        "status": status,
        "headers": headers or {},
        "body": {"text": text},
    }


def failed(text):
    return {"event_type": "request_failed", "url": TARGET, "failure_text": text}


@pytest.mark.parametrize(
    "event",
    [
        response(headers={"x-squid-error": "ERR_ACCESS_DENIED 0"}),
        response(503, headers={"X-Squid-Error": "ERR_DNS_FAIL 0"}),
        response(text="<p>Generated by egress-filter (squid)</p>"),
        response(text="URL blocked"),
        failed("net::ERR_TUNNEL_CONNECTION_FAILED"),
    ],
    ids=["squid-header", "squid-header-case", "squid-body", "crawl4ai-proxy", "refused-tunnel"],
)
def test_a_refusals_own_mark_passes(verify, event):
    assert verify.judge_event([event], TARGET)[0]


@pytest.mark.parametrize(
    "events",
    [
        [],
        [{"event_type": "request", "url": TARGET}],
        [response(200, text="ami-id")],
        [response(403, text="Forbidden")],
        [response(503, text="Service Unavailable")],
        [response(504)],
        [failed("net::ERR_CONNECTION_REFUSED")],
        [failed("net::ERR_INVALID_HTTP_RESPONSE")],
        [failed("net::ERR_BLOCKED_BY_CLIENT")],
        [failed("Unknown failure")],
        [{"event_type": "response_capture_error", "url": TARGET}],
        [response(text="URL blocked"), response(text="URL blocked")],
        [response(text="URL blocked", headers={}) | {"url": "http://other.example/"}],
    ],
    ids=[
        "no-event",
        "request-only",
        "200",
        "internal-403",
        "internal-503",
        "internal-504",
        "connection-refused",
        "bypassed-to-redis",
        "mixed-content",
        "unknown-failure",
        "capture-error",
        "two-events",
        "another-url",
    ],
)
def test_anything_else_fails(verify, events):
    assert not verify.judge_event(events, TARGET)[0]


@pytest.mark.parametrize(
    ("status", "answer"),
    [
        (400, {"detail": "URL blocked (SSRF protection): private"}),
        (200, {"success": False, "error_message": "URL blocked"}),
        (200, {"success": False, "error_message": "net::ERR_TUNNEL_CONNECTION_FAILED at x"}),
    ],
)
def test_a_refused_crawl_names_the_refusal(verify, status, answer):
    assert verify.judge_refused_crawl(status, answer)[0]


@pytest.mark.parametrize(
    ("status", "answer"),
    [
        (0, {"detail": "URLError"}),
        (401, {"detail": "no token"}),
        (422, {"detail": "bad body"}),
        (500, {"detail": "crash"}),
        (400, {"detail": "Rejected request: bad field"}),
        (200, {"success": True, "error_message": "URL blocked"}),
        (200, {"success": False, "error_message": "Page.goto timed out"}),
        (200, {"success": False}),
    ],
)
def test_a_crawl_that_failed_for_another_reason_fails(verify, status, answer):
    assert not verify.judge_refused_crawl(status, answer)[0]


def test_the_probe_page_holds_no_list_of_its_own(verify):
    page = (PATH.parent / "egress-probe.html").read_text(encoding="utf-8")

    assert "169.254" not in page
    assert "targets" in page
    assert "location" in page


def test_the_page_probes_the_addresses_chromium_could_bypass_a_proxy_for(verify):
    for target in (
        "http://localhost:11235/health",
        "http://127.0.0.1:11235/health",
        "http://[::1]:11235/health",
        "http://localhost:6379/",
        "http://127.0.0.1:6379/",
        "http://[::1]:6379/",
        "http://app:8000/healthz",
    ):
        assert target in verify.PAGE_TARGETS
