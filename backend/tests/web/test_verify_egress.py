def test_filter_says_asks_by_the_route_a_browser_would_use(verify, monkeypatch):
    asked = []

    def through_filter(method, target):
        asked.append((method, target))
        return 403, "ERR_ACCESS_DENIED", ""

    monkeypatch.setattr(verify, "through_filter", through_filter)

    assert verify.filter_says("https://10.0.0.1/x") == "ERR_ACCESS_DENIED"
    assert verify.filter_says("http://10.0.0.1/x") == "ERR_ACCESS_DENIED"
    assert asked == [("CONNECT", "10.0.0.1:443"), ("GET", "http://10.0.0.1/x")]


def test_only_the_filters_own_check_of_db_accepts_a_name_it_cannot_resolve(verify):
    allowed = [t for t, errors in verify.FILTER_GET.items() if errors != {"ERR_ACCESS_DENIED"}]

    assert allowed == ["http://db/"]
    assert verify.FILTER_GET["http://db/"] == {"ERR_DNS_FAIL"}


