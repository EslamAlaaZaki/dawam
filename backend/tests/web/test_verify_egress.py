"""The by-hand egress check must fail closed: its judges pass only on a refusal's own marks. The
script itself needs a running network, so only these pure parts run here."""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

PATH = Path(__file__).resolve().parents[3] / "deploy" / "crawl4ai" / "verify-egress.py"
TARGET = "http://169.254.169.254/"
CANARY = "dawam-egress-canary-7f3a"


@pytest.fixture(scope="module")
def verify():
    spec = importlib.util.spec_from_file_location("verify_egress", PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def response(status=403, *, headers=None, text=""):
    return {
        "event_type": "response",
        "url": TARGET,
        "status": status,
        "headers": headers or {},
        "body": {"text": text},
    }


def failed(text):
    return {"event_type": "request_failed", "url": TARGET, "failure_text": text}


@pytest.mark.parametrize(
    "event",
    [
        response(headers={"x-squid-error": "ERR_ACCESS_DENIED 0"}),
        response(headers={"X-Squid-Error": "ERR_ACCESS_DENIED 0"}),
        response(text="<p>ERR_ACCESS_DENIED. Generated by egress-filter (squid)</p>"),
        response(text="URL blocked"),
    ],
    ids=["squid-header", "squid-header-case", "squid-body", "crawl4ai-proxy"],
)
def test_a_refusals_own_mark_passes(verify, event):
    assert verify.judge_event([event], TARGET)[0]


TUNNEL = failed("net::ERR_TUNNEL_CONNECTION_FAILED")


def test_a_failed_tunnel_passes_only_once_the_filter_itself_refuses_the_address(verify):
    assert verify.judge_event([TUNNEL], TARGET, lambda _target: "ERR_ACCESS_DENIED")[0]


@pytest.mark.parametrize("error", [None, "ERR_CONNECT_FAIL", "ERR_DNS_FAIL", "ERR_READ_TIMEOUT"])
def test_a_failed_tunnel_the_filter_does_not_refuse_is_not_proven(verify, error):
    assert not verify.judge_event([TUNNEL], TARGET, lambda _target: error)[0]


def test_a_failed_tunnel_with_no_way_to_ask_the_filter_is_not_proven(verify):
    assert not verify.judge_event([TUNNEL], TARGET)[0]


@pytest.mark.parametrize(
    "error", ["ERR_CONNECT_FAIL", "ERR_READ_TIMEOUT", "ERR_DNS_FAIL", "ERR_ZERO_SIZE_OBJECT"]
)
def test_a_squid_error_that_is_not_a_refusal_fails_a_broken_acl_would_show_these(verify, error):
    event = response(503, headers={"X-Squid-Error": f"{error} 111"}, text="(squid)")

    assert not verify.judge_event([event], TARGET)[0]


def test_a_403_that_only_resembles_crawl4ais_refusal_fails(verify):
    assert not verify.judge_event([response(403, text="URL blocked by policy")], TARGET)[0]
    assert not verify.judge_event([response(200, text="URL blocked")], TARGET)[0]


