"use client";

import { ArrowRight } from "lucide-react";

import { PLATFORM_LABELS, useDataWarehouse } from "../api/dataWarehouse";
import { useDwTables } from "../api/dwModel";
import { useScore } from "../api/score";
import { useSourceSystems } from "../api/systems";
import {
  useStageProgress,
  type StageStatus,
  type Workspace,
} from "../api/workspaces";
import { Badge } from "../components/ui/badge";
import { Button } from "../components/ui/button";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "../components/ui/table";
import { cn } from "../lib/utils";
import { Loading } from "../shell/Loading";
import { EmptyState, ErrorText, h3Classes, monoClasses } from "./parts";
import { Big, Card } from "./overviewParts";
import { groupTables } from "./StagingModelPanel";

const STATUS_LABELS: Record<StageStatus, string> = {
  not_started: "Not started",
  in_progress: "In progress",
  complete: "Complete",
};

const STATUS_VARIANTS = {
  not_started: "neutral",
  in_progress: "accent",
  complete: "success",
} as const;

const GRADE_VARIANTS = {
  A: "success",
  B: "success",
  C: "warning",
  D: "danger",
  F: "danger",
} as const;

const SEVERITIES = [
  { severity: "error", one: "error", many: "errors", variant: "danger" },
  { severity: "warning", one: "warning", many: "warnings", variant: "warning" },
  { severity: "info", one: "info", many: "info", variant: "neutral" },
] as const;

const plural = (n: number, one: string, many: string) =>
  `${n} ${n === 1 ? one : many}`;

/**
 * The Staging Layer's root page: what the Layer holds, in three cards that open its Model,
 * Mappings and Evaluation folders, and the Staging Tables per Source System. `onOpen` takes
 * the folder's last path segment.
 */
export function StagingOverviewPanel({
  workspace,
  onOpen,
}: {
  workspace: Workspace;
  onOpen: (folder: string) => void;
}) {
  const tables = useDwTables(workspace.id, "staging");
  const systems = useSourceSystems(workspace.id);
  const warehouse = useDataWarehouse(workspace.id);
  const progress = useStageProgress(workspace.id);
  const score = useScore(workspace.id);

  const status = progress.data?.dw_modeling.find((l) => l.layer === "staging")
    ?.status;

  const header = (summary?: string) => (
    <header className="flex flex-col gap-2 border-b border-border pb-5 sm:flex-row sm:items-start">
      <div className="flex min-w-0 flex-1 flex-col gap-2">
        <h3
          id="folder-title"
          className={cn(h3Classes, "flex flex-wrap items-center gap-x-2 gap-y-1")}
        >
          Staging Layer
          {status && (
            <Badge variant={STATUS_VARIANTS[status]} dot>
              {STATUS_LABELS[status]}
            </Badge>
          )}
        </h3>
        <p className="text-sm text-muted-foreground">
          One Staging Table per source table, generated by DAWAM. Scored apart
          from the Data Warehouse.
        </p>
        {summary && (
          <p className="text-sm text-muted-foreground tabular-nums">
            {summary}
          </p>
        )}
      </div>
    </header>
  );

  if (tables.isPending) {
    return <Loading />;
  }
  if (tables.isError && !tables.data) {
    return (
      <section aria-labelledby="folder-title" className="flex flex-col gap-5">
        {header()}
        <ErrorText>
          Could not load the Staging Layer: {tables.error.message}
        </ErrorText>
      </section>
    );
  }
  const tableData = tables.data ?? [];

  if (tableData.length === 0) {
    return (
      <section aria-labelledby="folder-title" className="flex flex-col gap-5">
        {header()}
        <EmptyState title="No Staging Tables yet">
          Generate the Staging Layer on the Model page. Its mappings and
          evaluation show here once it exists.
          <span className="mt-3 block">
            <Button type="button" onClick={() => onOpen("model")}>
              Open Model
              <ArrowRight aria-hidden />
            </Button>
          </span>
        </EmptyState>
      </section>
    );
  }

  if (systems.isPending) {
    return <Loading />;
  }
  if (systems.isError) {
    return (
      <section aria-labelledby="folder-title" className="flex flex-col gap-5">
        {header()}
        <ErrorText>
          Could not load the Source Systems: {systems.error.message}
        </ErrorText>
      </section>
    );
  }

  const { groups, other } = groupTables(tableData, systems.data);
  const columns = tableData.reduce((sum, t) => sum + t.column_count, 0);
  const withIssues = tableData.filter(
    (t) => t.naming_violation_count > 0,
  ).length;
  const platform = warehouse.data?.target_platform
    ? PLATFORM_LABELS[warehouse.data.target_platform]
    : null;
  const summary = [
    plural(tableData.length, "table", "tables"),
    plural(columns, "column", "columns"),
    plural(groups.length, "Source System", "Source Systems"),
    platform,
  ]
    .filter(Boolean)
    .join(" · ");

  const layer = score.data?.layers.find((l) => l.layer === "staging");
  const scored = layer?.scored && layer.score != null ? layer : null;
  const failed = (score.data?.failed_checks ?? []).filter(
    (c) => c.layer === "staging",
  );

  const rows = [
    ...groups.map(({ system, schemas }) => {
      const items = schemas.flatMap((s) => s.tables);
      return {
        key: system.code,
        name: system.name,
        code: system.code,
        schemas: schemas.map((s) => s.name).join(", "),
        items,
      };
    }),
    ...(other.length > 0
      ? [{ key: "other", name: "Other", code: "", schemas: "", items: other }]
      : []),
  ];

  return (
    <section aria-labelledby="folder-title" className="flex flex-col gap-6">
      {header(summary)}
      {tables.isError && (
        <ErrorText>
          Could not refresh the Staging Layer: {tables.error.message}
        </ErrorText>
      )}
      <div className="grid grid-cols-1 gap-3 md:grid-cols-3">
        <Card
          name="Model"
          label={`Model: ${tableData.length} Staging Tables`}
          folder="dw/staging/model"
          onOpen={() => onOpen("model")}
        >
          <Big value={tableData.length} unit="Staging Tables" />
          {withIssues > 0 && (
            <Badge variant="warning" dot className="self-start">
              {withIssues} with naming issues
            </Badge>
          )}
        </Card>
        <Card
          name="Mappings"
          label={`Mappings: ${columns} columns`}
          folder="dw/staging/mappings"
          onOpen={() => onOpen("mappings")}
        >
          <Big value={columns} unit="columns" />
          <span className="text-sm text-muted-foreground">
            generated 1:1 from the source
          </span>
        </Card>
        <Card
          name="Evaluation"
          label={
            scored
              ? `Evaluation: score ${Math.round(scored.score ?? 0)}`
              : "Evaluation: not scored"
          }
          folder="dw/staging/evaluation"
          onOpen={() => onOpen("evaluation")}
        >
          {scored ? (
            <span className="flex items-baseline gap-2">
              <Big value={Math.round(scored.score ?? 0)} unit="/ 100" />
              {scored.grade && (
                <Badge variant={GRADE_VARIANTS[scored.grade]}>
                  Grade {scored.grade}
                </Badge>
              )}
            </span>
          ) : (
            <span className="text-md font-medium text-muted-foreground">
              Not scored
            </span>
          )}
          <span className="flex flex-wrap items-center gap-2 text-sm text-muted-foreground">
            {SEVERITIES.map(({ severity, one, many, variant }) => {
              const n = failed.filter((c) => c.severity === severity).length;
              return n > 0 ? (
                <Badge key={severity} variant={variant} dot>
                  {plural(n, one, many)}
                </Badge>
              ) : null;
            })}
            Not part of the DW score
          </span>
        </Card>
      </div>
      <section
        aria-labelledby="by-system-title"
        className="flex flex-col gap-3"
      >
        <h4
          id="by-system-title"
          className="text-xs font-medium tracking-wide text-subtle-foreground uppercase"
        >
          By Source System
        </h4>
        <div className="overflow-hidden rounded-pill border border-border">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Source System</TableHead>
                <TableHead>Database Schemas</TableHead>
                <TableHead className="text-end">Tables</TableHead>
                <TableHead className="text-end">Columns</TableHead>
                <TableHead className="text-end">Naming issues</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {rows.map((row) => (
                <TableRow key={row.key}>
                  <TableCell>
                    {row.name}
                    {row.code && (
                      <span
                        className={cn(monoClasses, "ms-2 text-muted-foreground")}
                      >
                        {row.code}
                      </span>
                    )}
                  </TableCell>
                  <TableCell className={monoClasses}>
                    {row.schemas || "-"}
                  </TableCell>
                  <TableCell className="text-end tabular-nums">
                    {row.items.length}
                  </TableCell>
                  <TableCell className="text-end tabular-nums">
                    {row.items.reduce((n, t) => n + t.column_count, 0)}
                  </TableCell>
                  <TableCell className="text-end tabular-nums">
                    {
                      row.items.filter((t) => t.naming_violation_count > 0)
                        .length
                    }
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </div>
      </section>
    </section>
  );
}
